#!/usr/bin/env python3
"""NOTES BATCH (owner PR pile-up order, Oct 28 2026 11:04 AM): 71 of 150 PRs in 25 h were notes/reports. Window reports, audits and claims
(branches needs/ report/ claim/ that change ONLY notes files) are held by the merge robot and joined here into ONE pull request per run
(hourly). Help-desk answers are not held (the Mac types them from main at once). A lone waiting PR is left to merge normally.
Originals are closed with a comment once the batch is merged. Environment: GH_TOKEN (the robot token), GITHUB_REPOSITORY."""
import json, os, re, subprocess, sys, time
REPO = os.environ.get("GITHUB_REPOSITORY", "Attacked-Kraken/18-Games-Casino")
NOTES = re.compile(r"^(jobs/[^/]+\.md|needs/[^/]+\.md|reviews/[^/]+\.md|CLAIMS\.md)$")
PREFIX = ("needs/", "report/", "claim/")

def gh(*a, method="GET", fields=None):
    cmd = ["gh", "api", "-X", method] + list(a)
    for k, v in (fields or {}).items(): cmd += ["-f", "%s=%s" % (k, v)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: print("gh failed", a, r.stderr[:200]); return None
    return json.loads(r.stdout) if r.stdout.strip() else {}

def git(*a, ok=False):
    r = subprocess.run(["git"] + list(a), capture_output=True, text=True)
    if r.returncode and not ok: print("git", a, r.stderr[:300])
    return r.returncode == 0, r.stdout

def main():
    # 1. close originals whose batch merged
    closed_recent = gh("repos/%s/pulls?state=closed&per_page=30&sort=updated&direction=desc" % REPO) or []
    for b in closed_recent:
        if b.get("merged_at") and b["title"].startswith("NOTES BATCH"):
            for n in re.findall(r"#(\d+)", (b.get("body") or "").split("Batched:")[-1]):
                o = gh("repos/%s/pulls/%s" % (REPO, n))
                if o and o.get("state") == "open" and o["number"] != b["number"]:
                    gh("repos/%s/issues/%s/comments" % (REPO, n), method="POST", fields={"body": "Merged inside notes batch #%d (its text is on main). Closed by the notes batcher." % b["number"]})
                    gh("repos/%s/pulls/%s" % (REPO, n), method="PATCH", fields={"state": "closed"})
                    print("closed original #%s (batch #%d merged)" % (n, b["number"]))
    opens = gh("repos/%s/pulls?state=open&per_page=100" % REPO) or []
    taken = set()
    for p in opens:
        if p["title"].startswith("NOTES BATCH"):
            taken |= set(re.findall(r"#(\d+)", (p.get("body") or "").split("Batched:")[-1]))
    cands = []
    for p in opens:
        br = p["head"]["ref"]
        if not br.startswith(PREFIX) or p.get("draft") or str(p["number"]) in taken: continue
        if p["head"]["repo"] is None or p["head"]["repo"]["full_name"] != REPO: continue
        fs = gh("repos/%s/pulls/%d/files?per_page=100" % (REPO, p["number"])) or []
        if not fs or not all(NOTES.match(f["filename"]) for f in fs): continue
        cands.append(p)
    print("batch candidates:", [c["number"] for c in cands])
    if len(cands) < 2:
        print("fewer than 2 waiting - nothing to batch (a lone PR merges normally)"); return
    stamp = time.strftime("%m%d-%H%M", time.gmtime())
    B = "robot/notes-batch-" + stamp
    git("config", "user.name", "notes batcher"); git("config", "user.email", "notes-batcher@users.noreply.github.com")
    git("fetch", "-q", "origin", "main"); git("checkout", "-q", "-B", B, "origin/main")
    done = []
    for p in cands:
        n = p["number"]
        git("fetch", "-q", "origin", "pull/%d/head:pr-%d" % (n, n))
        ok, _ = git("merge", "--no-edit", "-m", "notes batch: #%d %s" % (n, p["title"][:60]), "pr-%d" % n, ok=True)
        if ok: done.append(p)
        else:
            git("merge", "--abort", ok=True); print("#%d conflicts - left alone" % n)
    if len(done) < 2:
        print("fewer than 2 joined cleanly - no batch"); return
    git("push", "-q", "origin", B)
    lines = "\n".join("- #%d %s" % (p["number"], p["title"]) for p in done)
    title = "NOTES BATCH: %d notes (%s) PART: notes" % (len(done), ", ".join("#%d" % p["number"] for p in done[:6]))
    body = "One hourly pull request for notes that would each have been their own (owner PR pile-up order Oct 28 2026).\n\n%s\n\nBatched: %s\n\n🤖 Generated by the notes batcher" % (lines, " ".join("#%d" % p["number"] for p in done))
    r = gh("repos/%s/pulls" % REPO, method="POST", fields={"head": B, "base": "main", "title": title[:240], "body": body})
    print("opened batch", (r or {}).get("number"))
    subprocess.run(["gh", "workflow", "run", "game-check-pr.yml", "--ref", B])

if __name__ == "__main__":
    main()
